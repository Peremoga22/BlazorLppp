    public static ParsedTestDocument Create()
    {
        var document = new ParsedTestDocument
        {
            Title = CanonicalTitle,
            Instruction = CanonicalInstruction
        };

        for (var i = 0; i < Items.Length; i++)
        {
            var question = new ParsedTestQuestion
            {
                SortOrder = i + 1,
                Text = Items[i],
                Type = QuestionType.YesNo
            };
            question.Options.Add(new ParsedTestOption { SortOrder = 1, Key = "Так", Text = "Так" });
            question.Options.Add(new ParsedTestOption { SortOrder = 2, Key = "Ні", Text = "Ні" });
            document.Questions.Add(question);
        }

        return document;
    }
