    private static ParsedTestQuestion Single(
        int sortOrder,
        string text,
        string[] options,
        string? hint = null)
        => Build(sortOrder, text, options, QuestionType.SingleChoice, hint, null);

    private static ParsedTestQuestion Multi(
        int sortOrder,
        string text,
        string[] options,
        int? maxSelections = null)
        => Build(sortOrder, text, options, QuestionType.MultiChoice, null, maxSelections);

    private static ParsedTestQuestion Build(
        int sortOrder,
        string text,
        string[] options,
        QuestionType type,
        string? hint,
        int? maxSelections)
    {
        var question = new ParsedTestQuestion
        {
            SortOrder = sortOrder,
            Text = text,
            Hint = hint,
            Type = type,
            MaxSelections = maxSelections
        };

        for (var i = 0; i < options.Length; i++)
        {
            question.Options.Add(new ParsedTestOption
            {
                SortOrder = i + 1,
                Key = (i + 1).ToString(),
                Text = options[i]
            });
        }

        return question;
    }
