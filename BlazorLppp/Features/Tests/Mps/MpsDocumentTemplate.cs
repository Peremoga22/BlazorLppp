    public static MpsComponent? ComponentFor(int sortOrder)
        => Components.FirstOrDefault(c => sortOrder >= c.FirstQuestion && sortOrder <= c.LastQuestion);

    public static string? ItemText(int sortOrder)
        => sortOrder >= 1 && sortOrder <= ScaleItems.Length ? ScaleItems[sortOrder - 1] : null;

    public static ParsedTestDocument Create()
    {
        var document = new ParsedTestDocument
        {
            Title = CanonicalTitle,
            Instruction = CanonicalInstruction
        };

        for (var order = 1; order <= ScaleItems.Length; order++)
        {
            var component = ComponentFor(order);
            var hint = component is null
                ? "3. Мотиваційна готовність"
                : $"{Array.IndexOf(Components, component) + 1}. {component.Name}";

            if (order == MotivationQuestionOrder)
            {
                var multi = new ParsedTestQuestion
                {
                    SortOrder = order,
                    Text = MotivationQuestion,
                    Hint = hint,
                    Type = QuestionType.MultiChoice,
                    MaxSelections = 2
                };

                for (var i = 0; i < MotivationOptions.Length; i++)
                {
                    multi.Options.Add(new ParsedTestOption
                    {
                        SortOrder = i + 1,
                        Key = (i + 1).ToString(),
                        Text = MotivationOptions[i]
                    });
                }

                document.Questions.Add(multi);
                continue;
            }

            document.Questions.Add(new ParsedTestQuestion
            {
                SortOrder = order,
                Text = ScaleItems[order - 1]!,
                Hint = hint,
                Type = QuestionType.Scale,
                ScaleMin = ScaleMinValue,
                ScaleMax = ScaleMaxValue
            });
        }

        return document;
    }
